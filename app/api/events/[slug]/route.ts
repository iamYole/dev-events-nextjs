import { Event } from "@/database";
import connectToDatabase from "@/lib/mongodb";
import { NextResponse, type NextRequest } from "next/server";

type RouteContext = {
  params: Promise<{ slug: string }>;
};

export async function GET(_request: NextRequest, { params }: RouteContext) {
  let slugValue: unknown;
  try {
    ({ slug: slugValue } = await params);
  } catch (error) {
    console.error(error);
    return NextResponse.json({ message: "Failed to read event slug" }, { status: 500 });
  }

  if (typeof slugValue !== "string" || !slugValue.trim()) {
    return NextResponse.json({ message: "Invalid event slug" }, { status: 400 });
  }

  const slug = slugValue.trim();
  // Match URL-safe slugs generated by the Event model.
  if (!slug || slug.length > 200 || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    return NextResponse.json({ message: "Invalid event slug" }, { status: 400 });
  }

  try {
    await connectToDatabase();
    const event = await Event.findOne({ slug }).lean();
    if (!event) {
      return NextResponse.json({ message: "Event not found" }, { status: 404 });
    }

    return NextResponse.json({ message: "Event returned successfully", event }, { status: 200 });
  } catch (error) {
    console.error(error);
    return NextResponse.json({ message: "Failed to retrieve event" }, { status: 500 });
  }
}
